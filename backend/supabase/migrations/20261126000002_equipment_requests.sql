CREATE TABLE IF NOT EXISTS equipment_requests (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requester_id integer REFERENCES auth_users(id) ON DELETE SET NULL,
  requester_name varchar(201) NOT NULL,
  requester_username varchar(50) NOT NULL,
  category varchar(40) NOT NULL
    CHECK (category IN ('ordinateur_portable','ordinateur_fixe','ecran','telephone','accessoire','autre')),
  description text,
  justification text NOT NULL,
  priority varchar(20) NOT NULL DEFAULT 'moyenne'
    CHECK (priority IN ('basse','moyenne','haute')),
  status varchar(20) NOT NULL DEFAULT 'soumise'
    CHECK (status IN ('soumise','en_examen','approuvee','refusee','livree')),
  reviewer_id integer REFERENCES auth_users(id) ON DELETE SET NULL,
  decision_comment text,
  asset_id integer REFERENCES assets(id) ON DELETE SET NULL,
  affectation_id integer REFERENCES affectations(id) ON DELETE SET NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reviewed_at timestamp,
  delivered_at timestamp
);

CREATE INDEX IF NOT EXISTS idx_equipment_requests_requester
  ON equipment_requests(requester_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_equipment_requests_status
  ON equipment_requests(status, created_at DESC);
